package kb.data;

import java.util.List;

import com.zaxxer.hikari.HikariConfig;
import com.zaxxer.hikari.HikariDataSource;
import org.springframework.context.annotation.AnnotationConfigApplicationContext;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.data.annotation.Id;
import org.springframework.data.jdbc.repository.config.AbstractJdbcConfiguration;
import org.springframework.data.jdbc.repository.config.EnableJdbcRepositories;
import org.springframework.data.relational.core.mapping.Column;
import org.springframework.data.relational.core.mapping.MappedCollection;
import org.springframework.data.relational.core.mapping.Table;
import org.springframework.data.repository.CrudRepository;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcOperations;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcTemplate;
import org.springframework.jdbc.support.JdbcTransactionManager;
import org.springframework.transaction.PlatformTransactionManager;

public class JdbcAggregateDemo {
    @Table("ledger_payment")
    record LedgerPayment(@Id @Column("id") Long id, @Column("status") String status,
            @MappedCollection(idColumn = "payment_id", keyColumn = "line_index") List<LedgerLine> lines) {}

    @Table("ledger_line")
    record LedgerLine(@Column("account_id") String account, @Column("cents") long cents) {}

    public interface Ledger extends CrudRepository<LedgerPayment, Long> {}

    @Configuration(proxyBeanMethods = false)
    @EnableJdbcRepositories(basePackageClasses = JdbcAggregateDemo.class, considerNestedRepositories = true)
    static class Config extends AbstractJdbcConfiguration {
        @Bean(destroyMethod = "close") HikariDataSource dataSource() {
            var settings = new HikariConfig();
            settings.setJdbcUrl("jdbc:h2:mem:aggregate;DB_CLOSE_DELAY=-1");
            settings.setMaximumPoolSize(2);
            return new HikariDataSource(settings);
        }
        @Bean NamedParameterJdbcOperations namedParameterJdbcOperations(HikariDataSource dataSource) {
            return new NamedParameterJdbcTemplate(dataSource);
        }
        @Bean PlatformTransactionManager transactionManager(HikariDataSource dataSource) {
            return new JdbcTransactionManager(dataSource);
        }
    }

    public static void main(String[] args) {
        java.util.logging.Logger.getLogger("").setLevel(java.util.logging.Level.OFF);
        try (var context = new AnnotationConfigApplicationContext(Config.class)) {
            var jdbc = new JdbcTemplate(context.getBean(HikariDataSource.class));
            jdbc.execute("""
                    create table "ledger_payment" (
                        "id" bigint generated by default as identity primary key,
                        "status" varchar(40) not null)
                    """);
            jdbc.execute("""
                    create table "ledger_line" (
                        "row_token" bigint generated always as identity primary key,
                        "payment_id" bigint not null references "ledger_payment"("id"),
                        "line_index" int not null,
                        "account_id" varchar(40) not null,
                        "cents" bigint not null)
                    """);
            var repository = context.getBean(Ledger.class);
            var saved = repository.save(new LedgerPayment(null, "NEW", List.of(new LedgerLine("payer", 1_000))));
            long firstToken = token(jdbc);
            var changed = new LedgerPayment(saved.id(), "POSTED", saved.lines()); // Пока только новый объект Java.
            System.out.println("without save status=" + repository.findById(saved.id()).orElseThrow().status());
            repository.save(changed); // Обновляем корень и пересохраняем принадлежащие ему строки.
            System.out.println("after save status=" + repository.findById(saved.id()).orElseThrow().status());
            System.out.println("child row_token=" + firstToken + " -> " + token(jdbc));
            System.out.println("child count=" + jdbc.queryForObject("select count(*) from \"ledger_line\"", Long.class));
        }
    }

    static long token(JdbcTemplate jdbc) {
        return jdbc.queryForObject("select \"row_token\" from \"ledger_line\"", Long.class);
    }
}
